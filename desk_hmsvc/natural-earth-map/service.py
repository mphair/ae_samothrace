"""Natural Earth Map hmsvc -- serves the clipped, stripped-down Natural
Earth vector data in Data/naturalEarth/ (see
scripts/clip_natural_earth.py) over plain HTTP, for the Natural Earth
Map widget.

Deliberately much simpler than desk_hmsvc/samothrace-tiles/: that
service tiles and synthesizes *raster* imagery per z/x/y request, which
this project's Samothrace-site-scale plans genuinely need (multi-MB
mosaics, several derived layers computed per tile). This data is the
opposite shape -- a handful of already-small (<500 KB each) GeoJSON
files covering a whole 1000mi-ish box -- so there is nothing to tile or
compute per-request: every layer is just served whole, once, and the
browser's own HTTP cache (plus `fetch()` on the widget side) does the
rest. No MIN_ZOOM/MAX_ZOOM/TILE_SIZE here at all, unlike that service --
there's no tiling scheme for this hmsvc to agree with the widget on.

Self-discovering, same convention desk_hmsvc/samothrace-tiles/
service.py's own `_discover_keys` already uses: `/layers` is read
straight from Data/naturalEarth/metadata.json (written by
clip_natural_earth.py, right next to the .geojson files it describes)
rather than a second, hand-maintained list of layer ids/styles living
in this file. Re-running that script with a different bbox, filter, or
style is picked up here with no code change -- just re-fetch /layers.

Kept deliberately parallel to desk_hmsvc/samothrace-tiles/ in the
pieces that *are* shared shape (the `_project_dir()` pattern, CORS
setup, a 404-on-missing-file convention, a `/layers` endpoint as the
widget's one bootstrap call) specifically so a future merge of the two
widgets has less to reconcile -- see this directory's sibling widget,
desk_widgets/natural-earth-map/, for the matching rationale on that
side.

Run standalone for development: `uvicorn service:app --reload --port 8098`
(from this directory) -- DESK_PROJECT_DIR then needs to be set manually
since there's no Desk process to set it for you; see `_project_dir()`.
"""
import json
import os
import re
from pathlib import Path

from fastapi import FastAPI, Response
from fastapi.middleware.cors import CORSMiddleware


def _project_dir() -> Path:
    raw = os.environ.get("DESK_PROJECT_DIR")
    return Path(raw).resolve() if raw else Path.cwd().resolve()


PROJECT_DIR = _project_dir()
DATA_DIR = PROJECT_DIR / "Data" / "naturalEarth"
METADATA_PATH = DATA_DIR / "metadata.json"

# Layer ids are filenames with no extension, written by
# clip_natural_earth.py as plain `ne_<scale>_<name>` strings -- this
# pattern is just a defensive check before touching the filesystem with
# a request-supplied value, not a meaningful allowlist of its own (the
# real allowlist is "is this id present in metadata.json's own layers
# list right now," checked in `tile` below).
VALID_LAYER_ID = re.compile(r"^[a-zA-Z0-9_]+$")

app = FastAPI()
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)

# Short, not "immutable" (unlike samothrace-tiles' raster tiles, which
# are never regenerated in place) -- this data is small and can be
# regenerated by re-running clip_natural_earth.py at any time with a
# different bbox/filter, and this service doesn't restart (so doesn't
# get a fresh port) when that happens. A short cache still saves the
# browser from re-fetching the same ~1 MB of GeoJSON on every pan/zoom
# redraw within one session.
GEOJSON_HEADERS = {"Cache-Control": "public, max-age=60"}


def _read_metadata() -> dict | None:
    """Re-read on every call -- cheap (one small JSON file) and means a
    fresh `clip_natural_earth.py` run is picked up immediately, same
    reasoning as samothrace-tiles' own `_discover_keys` (no caching)."""
    if not METADATA_PATH.is_file():
        return None
    try:
        return json.loads(METADATA_PATH.read_text())
    except (OSError, ValueError):
        return None


@app.get("/layers")
def layers():
    metadata = _read_metadata()
    if metadata is None:
        return {"layers": [], "bounds": None, "center": None}
    return metadata


@app.get("/data/{layer_id}.geojson")
def data(layer_id: str):
    if not VALID_LAYER_ID.match(layer_id):
        return Response(status_code=404)
    metadata = _read_metadata()
    known_ids = {entry["id"] for entry in (metadata or {}).get("layers", [])}
    if layer_id not in known_ids:
        return Response(status_code=404)
    path = DATA_DIR / f"{layer_id}.geojson"
    if not path.is_file():
        return Response(status_code=404)
    return Response(content=path.read_bytes(), media_type="application/geo+json", headers=GEOJSON_HEADERS)
